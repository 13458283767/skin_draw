"""Control widgets only. MainWindow wires them to source and view actions."""

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QCheckBox, QComboBox, QFrame, QHBoxLayout, QLabel,
                               QProgressBar, QPushButton, QSlider, QSpinBox, QVBoxLayout, QWidget)

from ..colors import PALETTES
from ..filtering import DEFAULT_MAX_JUMP
from ..transport import BAUDRATES, DEFAULT_BAUDRATE
from ..simulator import DEMO_PRESETS, PATTERNS


def label(text: str, name: str = "muted") -> QLabel:
    widget = QLabel(text)
    widget.setObjectName(name)
    return widget


class ControlPanel(QFrame):
    def __init__(self, *, raw_adc=False):
        super().__init__()
        self.setObjectName("card")
        self.setMinimumWidth(235)
        box = QVBoxLayout(self)
        box.setContentsMargins(18, 18, 18, 18)
        box.setSpacing(10)
        box.addWidget(label("硬件连接", "section"))
        row = QHBoxLayout()
        self.port = QComboBox()
        self.port.setMinimumContentsLength(7)
        self.port.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
        self.refresh_ports = QPushButton("刷新")
        row.addWidget(self.port, 1)
        row.addWidget(self.refresh_ports)
        box.addLayout(row)
        box.addWidget(label("波特率 · 8N1 · RS485"))
        self.baudrate = QComboBox()
        for rate in BAUDRATES:
            self.baudrate.addItem(f"{rate}（{rate // DEFAULT_BAUDRATE} 倍）", rate)
        self.baudrate.setToolTip("选择与硬件固件一致的波特率；此处不会自动修改硬件波特率。切换前请先断开连接。")
        box.addWidget(self.baudrate)
        self.receive_mode = QComboBox()
        self.receive_mode.addItem("自动识别发送方式", "auto")
        self.receive_mode.addItem("连续接收（设备自动发送）", "stream")
        self.receive_mode.addItem("指令轮询（hello num）", "poll")
        self.receive_mode.setToolTip("自动模式先监听最多 2.3 秒；有数据直接接收，否则发送逐块采集指令。")
        box.addWidget(self.receive_mode)
        self.protocol = QComboBox()
        self.protocol.addItem("自动识别：明文 / 二进制", "auto")
        self.protocol.addItem("仅明文 BLOCK", "text")
        self.protocol.addItem("仅二进制 v0.5", "binary")
        self.protocol.setToolTip("二进制采用 v0.5：AA 帧头、大端 ADC、固定 0A 帧尾（始终校验），无 CRC。自动识别支持明文与 v0.5 二进制交替到达。")
        box.addWidget(self.protocol)
        self.connect_button = QPushButton("连接并显示" if raw_adc else "连接并校准")
        self.connect_button.setObjectName("primary")
        box.addWidget(self.connect_button)
        self.connection_status = label("请选择硬件串口")
        self.connection_status.setWordWrap(True)
        box.addWidget(self.connection_status)
        filter_note = label(f"有效点突变 > {DEFAULT_MAX_JUMP}：丢弃该行")
        filter_note.setWordWrap(True)
        filter_note.setToolTip(f"一行中任一有效点相对上一有效行对应点的 ADC 绝对变化超过 {DEFAULT_MAX_JUMP}，该行有效点保留上一有效值。隐藏空位不参与判断。其他行照常更新；下一帧该行全部有效点变化不超过 {DEFAULT_MAX_JUMP} 就立即放行。等于 {DEFAULT_MAX_JUMP} 保留，不设置固定 ADC 下限或基线差值上限。")
        if raw_adc:
            filter_note.setText("原始 ADC 模式 · 不过滤跳变")
            filter_note.setToolTip("直接显示协议解析后的读数，包括低值、零值和大幅跳变；不扣除基线。")
        box.addWidget(filter_note)
        box.addWidget(label("原始读数" if raw_adc else "无按压基线", "section"))
        self.calibration_progress = QProgressBar()
        self.calibration_progress.setRange(0, 100)
        self.calibration_progress.setValue(0)
        self.calibration_progress.setFormat("校准 %p%")
        box.addWidget(self.calibration_progress)
        self.calibration_status = label("保持无按压，各行累计约1秒且至少30个有效样本")
        self.calibration_status.setWordWrap(True)
        box.addWidget(self.calibration_status)
        self.calibration_details = label("")
        self.calibration_details.setWordWrap(True)
        self.calibration_details.hide()
        box.addWidget(self.calibration_details)
        self.recalibrate = QPushButton("重新校准基线")
        self.recalibrate.setEnabled(False)
        box.addWidget(self.recalibrate)
        self.direction = QPushButton("受压变小 ↓  · 点击切换")
        self.direction.setToolTip("默认响应 = 基线 − 当前 ADC；可切换为当前 ADC − 基线。")
        box.addWidget(self.direction)
        if raw_adc:
            self.calibration_status.setText("收到首帧立即绘图，无需校准。")
            for widget in (self.calibration_progress, self.recalibrate, self.direction):
                widget.setEnabled(False)
                widget.hide()
        box.addSpacing(5)
        box.addWidget(label("皮肤块布局", "section"))
        note = label("可按人体正面、背面预设摆放，\n或自动排列实际连接的皮肤块。")
        note.setWordWrap(True)
        box.addWidget(note)
        self.detected = label("等待数据")
        self.detected.setWordWrap(True)
        box.addWidget(self.detected)
        self.body_positions = QPushButton("恢复人体预设（14块）")
        self.body_positions.setToolTip("按示意图①～⑭对应BLOCK 1～14恢复位置；未连接部位显示占位框。保留已有旋转、镜像及数据状态。")
        box.addWidget(self.body_positions)
        self.reset_positions = QPushButton("恢复自动排列")
        self.reset_positions.setEnabled(False)
        self.reset_positions.setToolTip("清除所有皮肤块的手动位置，保留各块旋转和镜像方向。")
        box.addWidget(self.reset_positions)
        note = label("按住 BLOCK 标题或彩色区域，\n单独拖动这一块皮肤；\n其他皮肤块保持不动。")
        note.setWordWrap(True)
        box.addWidget(note)
        box.addSpacing(7)
        box.addWidget(label("皮肤块方向", "section"))
        self.orientation_block = QComboBox()
        self.orientation_block.setToolTip("选择要调整的皮肤块，也可以直接点击图中的传感器。")
        box.addWidget(self.orientation_block)
        row = QHBoxLayout()
        self.rotate_left = QPushButton("左转 90°")
        self.rotate_right = QPushButton("右转 90°")
        row.addWidget(self.rotate_left)
        row.addWidget(self.rotate_right)
        box.addLayout(row)
        row = QHBoxLayout()
        self.mirror_horizontal = QPushButton("左右镜像")
        self.mirror_vertical = QPushButton("上下镜像")
        row.addWidget(self.mirror_horizontal)
        row.addWidget(self.mirror_vertical)
        box.addLayout(row)
        self.reset_orientation = QPushButton("恢复原始方向")
        box.addWidget(self.reset_orientation)
        self.edit_sensor_mask = QPushButton("编辑有效点位")
        self.edit_sensor_mask.setEnabled(False)
        self.edit_sensor_mask.setToolTip("为上方选中的 BLOCK 指定有传感器的格子，空位不显示、不参与统计；原始矩阵保持完整。")
        box.addWidget(self.edit_sensor_mask)
        self.mask_status = label("有效点位按 BLOCK 编号保存，重启自动恢复。")
        self.mask_status.setWordWrap(True)
        box.addWidget(self.mask_status)
        note = label("仅调整所选皮肤块。\n方向在本次运行期间保留。")
        note.setWordWrap(True)
        box.addWidget(note)
        for widget in (self.orientation_block, self.rotate_left, self.rotate_right,
                       self.mirror_horizontal, self.mirror_vertical, self.reset_orientation):
            widget.setEnabled(False)
        box.addSpacing(7)
        box.addWidget(label("颜色与方块", "section"))
        self.palette = QComboBox()
        self.palette.addItems(PALETTES)
        box.addWidget(self.palette)
        row = QHBoxLayout()
        self.low, self.high = QSpinBox(), QSpinBox()
        for spin in (self.low, self.high):
            spin.setRange(0, 4095)
            spin.setKeyboardTracking(False)
        self.high.setValue(4095)
        row.addWidget(self.low)
        row.addWidget(label("—"))
        row.addWidget(self.high)
        box.addLayout(row)
        self.auto_levels = QCheckBox("按当前帧自动色阶")
        self.auto_levels.setToolTip("比较按压力度请关闭：固定色阶下，相同 ΔADC 始终对应相同颜色。")
        if raw_adc:
            self.auto_levels.setToolTip("默认固定 0–4095 色阶，相同 ADC 对应相同颜色；可调整上下限观察细微变化。")
        box.addWidget(self.auto_levels)
        self.show_values = QCheckBox("方块内显示数值")
        self.show_values.setChecked(raw_adc)
        self.show_values.setToolTip("方块太小时隐藏数值；放大后自动显示。悬停始终可读数。")
        box.addWidget(self.show_values)
        row = QHBoxLayout()
        row.addWidget(label("方块间距"))
        self.gap = QSlider(Qt.Orientation.Horizontal)
        self.gap.setRange(0, 25)
        self.gap.setValue(10)
        row.addWidget(self.gap, 1)
        box.addLayout(row)
        box.addSpacing(7)
        self.demo_toggle = QCheckBox("使用模拟数据测试")
        box.addWidget(self.demo_toggle)
        self.demo_panel = QWidget()
        demo_box = QVBoxLayout(self.demo_panel)
        demo_box.setContentsMargins(0, 0, 0, 0)
        self.preset = QComboBox()
        self.preset.addItems(DEMO_PRESETS)
        self.preset.setToolTip("仅切换模拟输入数据规模。真实数据无需选择块数或尺寸。")
        demo_box.addWidget(self.preset)
        self.pattern = QComboBox()
        self.pattern.addItems(PATTERNS)
        demo_box.addWidget(self.pattern)
        row = QHBoxLayout()
        self.play = QPushButton("暂停演示")
        self.play.setObjectName("primary")
        self.step = QPushButton("单步")
        row.addWidget(self.play, 1)
        row.addWidget(self.step)
        demo_box.addLayout(row)
        note = label("这里仅切换模拟输入。\n真实数据无需手动设置尺寸。")
        note.setWordWrap(True)
        demo_box.addWidget(note)
        box.addWidget(self.demo_panel)
        self.demo_panel.hide()
        box.addStretch(1)
